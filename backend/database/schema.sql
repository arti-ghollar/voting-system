CREATE DATABASE IF NOT EXISTS voting_system;
USE voting_system;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  fullName VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role ENUM('VOTER', 'ADMIN') DEFAULT 'VOTER',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS voters (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  voterId VARCHAR(255) NOT NULL UNIQUE,
  is_verified BOOLEAN DEFAULT FALSE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  department VARCHAR(255),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS elections (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT,
  status ENUM('UPCOMING', 'ACTIVE', 'COMPLETED') DEFAULT 'UPCOMING',
  startDate DATETIME NOT NULL,
  endDate DATETIME NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS candidates (
  id INT AUTO_INCREMENT PRIMARY KEY,
  electionId INT NOT NULL,
  name VARCHAR(255) NOT NULL,
  party VARCHAR(255),
  description TEXT,
  photo TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (electionId) REFERENCES elections(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS votes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  electionId INT NOT NULL,
  candidateId INT NOT NULL,
  voterId INT NOT NULL,
  voted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (electionId) REFERENCES elections(id) ON DELETE CASCADE,
  FOREIGN KEY (candidateId) REFERENCES candidates(id) ON DELETE CASCADE,
  FOREIGN KEY (voterId) REFERENCES voters(id) ON DELETE CASCADE,
  UNIQUE(electionId, voterId)
);

CREATE TABLE IF NOT EXISTS election_candidates (
  electionId INT NOT NULL,
  candidateId INT NOT NULL,
  PRIMARY KEY (electionId, candidateId),
  FOREIGN KEY (electionId) REFERENCES elections(id) ON DELETE CASCADE,
  FOREIGN KEY (candidateId) REFERENCES candidates(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS results (
  id INT AUTO_INCREMENT PRIMARY KEY,
  electionId INT NOT NULL,
  candidateId INT NOT NULL,
  totalVotes INT DEFAULT 0,
  FOREIGN KEY (electionId) REFERENCES elections(id) ON DELETE CASCADE,
  FOREIGN KEY (candidateId) REFERENCES candidates(id) ON DELETE CASCADE
);
